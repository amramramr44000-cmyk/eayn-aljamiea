  bucket_id='id-documents' and (public.is_admin() or (storage.foldername(name))[1]=auth.uid()::text)
);
drop policy if exists id_docs_insert on storage.objects;
create policy id_docs_insert on storage.objects for insert to authenticated with check (
  bucket_id='id-documents' and (storage.foldername(name))[1]=auth.uid()::text
);

drop policy if exists report_photos_select on storage.objects;
create policy report_photos_select on storage.objects for select to authenticated using (
  bucket_id='report-photos' and (
    public.is_admin()
    or (storage.foldername(name))[1]=auth.uid()::text
    or exists(select 1 from public.reports r where r.public_code=(storage.foldername(name))[2] and r.assigned_staff_id=auth.uid())
  )
);
