-- Profiles
 drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles for select to authenticated using (
  id=auth.uid() or public.is_admin() or (public.is_staff() and role='student')
);
drop policy if exists profiles_insert on public.profiles;
create policy profiles_insert on public.profiles for insert to authenticated with check (id=auth.uid() and role='student');
drop policy if exists profiles_admin_update on public.profiles;
create policy profiles_admin_update on public.profiles for update to authenticated using (public.is_admin()) with check (public.is_admin());
-- الطالب يستطيع استكمال بيانات ملفه فقط وهو ما يزال pending؛ لا يستطيع اعتماد نفسه.
drop policy if exists profiles_student_pending_update on public.profiles;
create policy profiles_student_pending_update on public.profiles for update to authenticated
using (id=auth.uid() and role='student' and account_status='pending')
with check (id=auth.uid() and role='student' and account_status='pending');

-- Reports
 drop policy if exists reports_select on public.reports;
create policy reports_select on public.reports for select to authenticated using (
  reporter_id=auth.uid()
  or public.is_admin()
  or (public.is_staff() and (assigned_staff_id=auth.uid() or (assigned_staff_id is null and category=(select p.center_category from public.profiles p where p.id=auth.uid()))))
);
drop policy if exists reports_insert on public.reports;
create policy reports_insert on public.reports for insert to authenticated with check (reporter_id=auth.uid() and public.is_approved_student(auth.uid()));
drop policy if exists reports_admin_update on public.reports;
create policy reports_admin_update on public.reports for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists reports_staff_update on public.reports;
create policy reports_staff_update on public.reports for update to authenticated using (public.is_staff() and assigned_staff_id=auth.uid()) with check (public.is_staff() and assigned_staff_id=auth.uid());

-- Updates
 drop policy if exists report_updates_select on public.report_updates;
create policy report_updates_select on public.report_updates for select to authenticated using (
  exists(select 1 from public.reports r where r.id=report_id and (r.reporter_id=auth.uid() or public.is_admin() or (public.is_staff() and r.assigned_staff_id=auth.uid())))
);
drop policy if exists report_updates_insert on public.report_updates;
create policy report_updates_insert on public.report_updates for insert to authenticated with check (
  actor_id=auth.uid() and exists(select 1 from public.reports r where r.id=report_id and (public.is_admin() or (public.is_staff() and r.assigned_staff_id=auth.uid())))
);

-- Notifications
drop policy if exists notifications_select on public.notifications;
create policy notifications_select on public.notifications for select to authenticated using (user_id=auth.uid() or public.is_admin());
drop policy if exists notifications_insert on public.notifications;
create policy notifications_insert on public.notifications for insert to authenticated with check (public.is_admin() or user_id=auth.uid());
drop policy if exists notifications_update on public.notifications;
create policy notifications_update on public.notifications for update to authenticated using (user_id=auth.uid()) with check (user_id=auth.uid());

-- Rewards
drop policy if exists rewards_select on public.rewards;
create policy rewards_select on public.rewards for select to authenticated using (active=true or public.is_admin());
drop policy if exists rewards_admin on public.rewards;
create policy rewards_admin on public.rewards for all to authenticated using (public.is_admin()) with check (public.is_admin());

