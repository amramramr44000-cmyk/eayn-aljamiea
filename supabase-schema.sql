-- إشعار الإدارة عند وصول بلاغ جديد.
create or replace function public.notify_admins_new_report()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.notifications(user_id,report_id,title,body)
  select p.id,new.id,'بلاغ جديد وارد', 'وصل البلاغ '||new.public_code||' إلى الإدارة العليا ضمن مسار '||new.category||'.'
  from public.profiles p
  where p.role='admin' and p.account_status='approved';
  return new;
end;
$$;
drop trigger if exists trg_report_notify_admins on public.reports;
create trigger trg_report_notify_admins after insert on public.reports for each row execute function public.notify_admins_new_report();

-- إشعار الإدارة عند طلب إنشاء حساب جديد.
create or replace function public.notify_admins_new_account()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if new.role='student' and new.account_status='pending' then
    insert into public.notifications(user_id,title,body)
    select p.id,'طلب حساب جامعي جديد','يوجد طلب حساب جديد باسم '||coalesce(new.full_name,'غير محدد')||'.'
    from public.profiles p
    where p.role='admin' and p.account_status='approved';
  end if;
  return new;
end;
$$;
drop trigger if exists trg_profile_notify_admins on public.profiles;
create trigger trg_profile_notify_admins after insert on public.profiles for each row execute function public.notify_admins_new_account();


